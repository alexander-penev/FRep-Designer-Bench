#!/bin/sh
# paper_numbers.sh — regenerate every measured number the paper reports.
#
# The suite's run_all.sh covers the cross-system grid and native-render
# comparison. It does not cover FRep Designer's own GPU paths, which is where
# most of the paper's claims live, so those numbers used to be produced by hand
# and existed only in the manuscript. This script closes that gap: one command
# regenerates each table into results/paper/, so a claim can always be traced
# back to a run, and a code change that moves a number is caught by re-running
# rather than by noticing.
#
# Usage:
#   ./paper_numbers.sh              # everything (needs the GPU build)
#   ./paper_numbers.sh render       # one section: render|resolution|hetero|rtx|grid
#
# Requires the render build (frep4_bench/build_render). Build it with:
#   cmake -S frep4_bench -B frep4_bench/build_render -G Ninja \
#         -DCMAKE_BUILD_TYPE=Release -DFREP4_BENCH_RENDER=ON && \
#   ninja -C frep4_bench/build_render
set -e
cd "$(dirname "$0")"

# The per-cell medians are computed in awk, which parses and prints numbers
# in the caller's locale: under a decimal-comma locale "1.683" reads as 1 and
# every median prints with a comma, so the table is wrong in a way the CSV
# header does not reveal. The tools print C-locale CSV; match it here.
export LC_ALL=C

BIN=frep4_bench/build_render
OUT=results/paper

# Energy is read from the RAPL package counter, and there are two ways to reach
# it. The powercap file is root-only on a stock distribution (a mitigation for
# PLATYPUS, which recovered keys from RAPL traces), so everything here goes
# through the perf_event PMU instead -- which needs kernel.perf_event_paranoid
# at 0 or below. Without it nothing breaks and nothing errors: every joules
# column silently becomes -1, the tables render dashes, and the energy axis
# quietly stops existing. That failure is invisible in the output, which is why
# it is checked here rather than discovered in a table.
paranoid=$(cat /proc/sys/kernel/perf_event_paranoid 2>/dev/null || echo 99)
if [ "$paranoid" -gt 0 ] 2>/dev/null; then
    echo "paper_numbers.sh: kernel.perf_event_paranoid is $paranoid; RAPL is" >&2
    echo "  unreadable and every energy column will be a dash. Fix with:" >&2
    echo "    sudo sysctl -w kernel.perf_event_paranoid=0" >&2
    echo "  and persist it in /etc/sysctl.d/99-perf.conf. Set" >&2
    echo "  FREP_ALLOW_NO_ENERGY=1 to regenerate the timing tables anyway." >&2
    [ -n "$FREP_ALLOW_NO_ENERGY" ] || exit 1
fi
SCENES="s1_sphere s2_csg s3_blend s4_gyroid s5_twist c1_gear c2_colonnade"
HDR="system,backend,scene,metric,size,ms,throughput,joules,uj_per_unit"

# The CPU band leaves cores for the GPU submit thread; on a many-core host the
# CPU executor otherwise oversubscribes and both paths lose. See the heterogeneous
# subsection: this is a scheduling parameter, not a tuning trick.
CPU_THREADS=${FREP4_CPU_THREADS:-14}

mkdir -p "$OUT"
need() {
    [ -x "$BIN/$1" ] || { echo "missing $BIN/$1 — build the render targets first" >&2; exit 1; }
}

# The GPU paths are measured with the process bound to the socket the card is
# attached to. On this two-socket host the scheduler placed the process on the
# other socket two runs in three, and every readback then crossed QPI: at 512²
# GPU_IR went 0.67–0.72 → 1.00–1.01 ms, GPU_RTX 0.63–0.71 → 0.82, GPU_GLSL
# 0.54–0.56 → 0.63. The CPU path keeps every core (it is run unbound, in a
# separate process). FREP_GPU_NODE=<n> overrides the node; FREP_GPU_NODE= (empty)
# disables the binding; a host without numactl or NUMA information runs unbound.
gpu_node() {
    if [ -n "${FREP_GPU_NODE+set}" ]; then echo "$FREP_GPU_NODE"; return; fi
    command -v numactl >/dev/null 2>&1 || return 0
    bdf=$(nvidia-smi --query-gpu=pci.bus_id --format=csv,noheader 2>/dev/null | head -1 | tr 'A-F' 'a-f')
    bdf=${bdf#0000}                      # 00000000:07:00.0 -> 0000:07:00.0
    n=$(cat "/sys/bus/pci/devices/$bdf/numa_node" 2>/dev/null)
    [ -n "$n" ] && [ "$n" -ge 0 ] 2>/dev/null && echo "$n"
}
GPU_NODE=$(gpu_node)
bind_gpu() { if [ -n "$GPU_NODE" ]; then numactl -N "$GPU_NODE" -m "$GPU_NODE" "$@"; else "$@"; fi; }

provenance() {
    {
        echo "# generated by paper_numbers.sh on $(date -Is)"
        echo "# commit: $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
        echo "# host:   $(uname -sr) / $(nproc) cores"
        echo "# gpu:    $(nvidia-smi --query-gpu=name --format=csv,noheader 2>/dev/null || echo none)"
        echo "# gpu numa node: ${GPU_NODE:-unbound} (GPU paths bound with numactl when set; CPU path unbound)"
    } > "$1"
}

# One pathcost measurement in two halves: the CPU path with every core, then
# the three GPU paths bound to the card's node. $1 is the CSV to append to.
pathcost_both() {
    out=$1; shift
    FREP_PATHS=cpu_ir "$BIN/frep4_pathcost" "$@" 2>>"$out" >/dev/null
    FREP_PATHS=gpu_glsl,gpu_ir,gpu_rtx bind_gpu "$BIN/frep4_pathcost" "$@" 2>>"$out" >/dev/null
}

# Per-cell median of several runs of the same CSV (ms, build_ms, run_ms;
# throughput recomputed from the median ms). Keeps the first run's header.
median_csv() {
    out=$1; shift
    {
        grep '^#' "$1"
        echo "# per-cell median of $# runs (ms, build_ms, run_ms)"
        grep -v '^#' "$1" | head -1
        awk -F, '/^#/ || $1 != "frep4" {next}
            { k=$1","$2","$3","$4","$5
              if (!(k in seen)) { seen[k]=1; key[++n]=k; sz[k]=$5 }
              w[k]=w[k]" "$6; b[k]=b[k]" "$10; r[k]=r[k]" "$11 }
            function med(s,  a,m,i,j,t) {
              m=split(s,a," "); for(i=1;i<=m;i++) a[i]+=0
              for(i=2;i<=m;i++){ t=a[i]; j=i-1; while(j>0 && a[j]>t){ a[j+1]=a[j]; j-- } a[j+1]=t }
              return a[int((m+1)/2)] }
            END { for(i=1;i<=n;i++){ k=key[i]; mw=med(w[k])
                    printf "%s,%.3f,%.3f,-1.0000,-1.0000,%.2f,%.3f\n", k, mw, sz[k]*sz[k]/mw/1e3, med(b[k]), med(r[k]) } }' "$@"
    } > "$out.tmp" && mv "$out.tmp" "$out"
}

# ── Render cost per path, one resolution (the cross-system render table) ──────
#
# Two shading levels, because the cross-system table is otherwise not
# like-for-like. libfive's Heightmap::render and mpr's render3D produce depth
# plus a surface normal and stop; our default also runs a shadow march, five
# ambient-occlusion samples and a specular term at every hit, each of which is
# another evaluation of the whole field. render_512.csv is the matched level
# (what the other systems compute) and is what the comparison table reports;
# render_512_full.csv is the shading model the application ships with, and the
# difference between them is the price of that model.
# Each table is a per-cell median of RENDER_RUNS (default 3) complete runs:
# a single run's GPU cells moved by up to 25% between repetitions.
do_render() {
    need frep4_pathcost
    runs=${RENDER_RUNS:-3}
    for lvl in matched full; do
        if [ "$lvl" = matched ]; then f="$OUT/render_512.csv"; shade=--geometry
        else f="$OUT/render_512_full.csv"; shade=""; fi
        files=""; i=1
        while [ "$i" -le "$runs" ]; do
            fr="$OUT/.render_${lvl}_run$i.csv"; provenance "$fr"; echo "$HDR,build_ms,run_ms" >> "$fr"
            for s in $SCENES; do pathcost_both "$fr" "scenes/frep4/$s.json" 512 $shade; done
            files="$files $fr"; i=$((i+1))
        done
        median_csv "$f" $files
        rm -f $files
        echo "-> $f"
    done
}

# ── CPU vs GPU across frame sizes (the resolution-scaling table) ─────────────
do_resolution() {
    need frep4_pathcost
    f="$OUT/render_scaling.csv"; provenance "$f"; echo "$HDR,build_ms,run_ms" >> "$f"
    for r in 400 800 1280; do
        for s in $SCENES; do
            pathcost_both "$f" "scenes/frep4/$s.json" "$r"
        done
    done
    echo "-> $f"
}

# ── Heterogeneous throughput + energy (shared tile queue) ────────────────────
do_hetero() {
    need frep4_tilequeue_bench
    f="$OUT/hetero_tilequeue.csv"; provenance "$f"; echo "$HDR" >> "$f"
    set -- ; for s in $SCENES; do set -- "$@" "scenes/frep4/$s.json"; done
    FREP4_CPU_THREADS="$CPU_THREADS" bind_gpu "$BIN/frep4_tilequeue_bench" "$@" \
        --res 800 --tile 128 --frames 10 --rounds 5 2>>"$f"
    echo "-> $f"
}

# ── RTX multi-BLAS instance scaling ─────────────────────────────────────────
do_rtx() {
    [ -x "$BIN/frep4/frep_rtx_bench" ] || {
        echo "skip rtx: $BIN/frep4/frep_rtx_bench not built" >&2; return 0; }
    f="$OUT/rtx_instances.txt"; provenance "$f"
    "$BIN/frep4/frep_rtx_bench" --energy >> "$f" 2>&1 || true
    echo "-> $f"
}

# ── Grid SDF-evaluation throughput (cross-system comparison) ────────────────
do_grid() {
    need frep4_bench_grid
    f="$OUT/grid_193.csv"; provenance "$f"; echo "$HDR" >> "$f"
    set -- ; for s in $SCENES; do set -- "$@" "scenes/frep4/$s.json"; done
    "$BIN/frep4_bench_grid" 193 "$@" >> "$f"
    echo "-> $f"
}

# ── Cross-system energy on one identical workload ───────────────────────────
# The energy axis is only meaningful across systems if the systems do the same
# work. The 193^3 grid is the one workload all three scalar evaluators perform
# (mpr is a GPU interval renderer and exposes no scalar evaluation), and the
# three agree on the field to ~1e-7, so the joules differ only in how each
# evaluates it. Energy is whole-package CPU (RAPL) plus GPU (NVML) over the run
# -- energy to complete the task, which is what a user pays.
do_energy() {
    need frep4_energy_wrap
    W="$BIN/frep4_energy_wrap"
    f="$OUT/energy_xsys.csv"; provenance "$f"; echo "$HDR" >> "$f"

    LB=libfive_bench/build/bench_libfive
    HF=hyperfun_bench/build/bench_hf
    if [ -x "$LB" ]; then
        export LD_LIBRARY_PATH="${LIBFIVE_ROOT:-$(pwd)/libfive}/build/libfive/src:$LD_LIBRARY_PATH"
        "$W" libfive cpu-array grid193 193 -- "$LB" --grid 193 >>"$f" 2>/dev/null
    else echo "skip libfive (not built)" >&2; fi

    if [ -x "$HF" ]; then
        set -- ; for s in $SCENES; do [ -f "scenes/hyperfun/$s.hf" ] && set -- "$@" "scenes/hyperfun/$s.hf"; done
        [ $# -gt 0 ] && "$W" hyperfun interpreter grid193 193 -- "$HF" 193 "$@" >>"$f" 2>/dev/null
    else echo "skip hyperfun (not built)" >&2; fi

    set -- ; for s in $SCENES; do set -- "$@" "scenes/frep4/$s.json"; done
    "$W" frep4 cpu_ir grid193 193 -- "$BIN/frep4_bench_grid" 193 "$@" >>"$f" 2>/dev/null
    echo "-> $f"
}

# ── Energy per render path (the CPU/GPU split of the energy axis) ───────────
# Both counters over a fixed-duration window per path: NVML integrates power on
# a ~10-100 ms cadence, so a few millisecond-scale frames sample nothing. CPU
# and GPU are reported separately because the package draws ~80 W on this host
# whatever the GPU is doing, so a single total would price a GPU path by how
# long the CPU waited for it.
do_pathenergy() {
    need frep4_pathcost
    f="$OUT/energy_paths.csv"; provenance "$f"
    echo "$HDR,gpu_j_per_frame,cpu_j_per_frame,build_ms,run_ms" >> "$f"
    for s in $SCENES; do
        pathcost_both "$f" "scenes/frep4/$s.json" 512 --energy 6
    done
    echo "-> $f"
}

# ── Per-frame marginal energy at the matched shading level ──────────────────
# The cross-system energy table compares against libfive and mpr, which
# compute depth + normal only, so our side is measured at that level too
# (--geometry), over the same 5 s window their drivers use.
do_renderenergy() {
    need frep4_pathcost
    f="$OUT/energy_render.csv"; provenance "$f"
    echo "$HDR,gpu_j_per_frame,cpu_j_per_frame,build_ms,run_ms" >> "$f"
    for s in $SCENES; do
        pathcost_both "$f" "scenes/frep4/$s.json" 512 --geometry --energy 5
    done
    echo "-> $f"
}

# ── CPU thread-count sweep on the colonnade (the race-to-idle check) ────────
# Energy per frame against the number of cores the CPU path may use; the
# paper's argument that finishing sooner costs less in total rests on this.
do_threads() {
    need frep4_pathcost
    f="$OUT/threads_colonnade.csv"; provenance "$f"
    echo "threads,$HDR,gpu_j_per_frame,cpu_j_per_frame,build_ms,run_ms" >> "$f"
    for t in 8 14 28 56; do
        FREP4_CPU_THREADS=$t FREP_PATHS=cpu_ir "$BIN/frep4_pathcost" "scenes/frep4/c2_colonnade.json" 512 --geometry --energy 5 \
            2>&1 >/dev/null | grep '^frep4,' | sed "s/^/$t,/" >> "$f"
    done
    echo "-> $f"
}

case "${1:-all}" in
    render)     do_render ;;
    resolution) do_resolution ;;
    hetero)     do_hetero ;;
    rtx)        do_rtx ;;
    grid)       do_grid ;;
    energy)     do_energy ;;
    pathenergy) do_pathenergy ;;
    renderenergy) do_renderenergy ;;
    threads)    do_threads ;;
    all)        do_render; do_resolution; do_hetero; do_rtx; do_grid; do_energy; do_pathenergy; do_renderenergy; do_threads ;;
    *) echo "usage: $0 [all|render|resolution|hetero|rtx|grid|energy|pathenergy|renderenergy|threads]" >&2; exit 2 ;;
esac

echo "done — CSVs in $OUT/ (see $OUT/README.md for the table mapping)"
