#!/bin/sh
# paper_numbers.sh — regenerate every measured number the paper reports.
#
# The suite's run_all.sh covers the cross-system grid and native-render
# comparison. It does not cover FRep Designer's own GPU paths, which is where
# most of the paper's claims live, so those numbers used to be produced by hand
# and existed only in the manuscript. This script closes that gap: one command
# regenerates each table into results/paper/, so a claim can always be traced
# back to a run, and a code change that moves a number is caught by re-running
# rather than by noticing.
#
# Usage:
#   ./paper_numbers.sh              # everything (needs the GPU build)
#   ./paper_numbers.sh render       # one section: render|resolution|hetero|rtx|grid
#
# Requires the render build (frep4_bench/build_render). Build it with:
#   cmake -S frep4_bench -B frep4_bench/build_render -G Ninja \
#         -DCMAKE_BUILD_TYPE=Release -DFREP4_BENCH_RENDER=ON && \
#   ninja -C frep4_bench/build_render
set -e
cd "$(dirname "$0")"

BIN=frep4_bench/build_render
OUT=results/paper
SCENES="s1_sphere s2_csg s3_blend s4_gyroid s5_twist c1_gear c2_colonnade"
HDR="system,backend,scene,metric,size,ms,throughput,joules,uj_per_unit"

# The CPU band leaves cores for the GPU submit thread; on a many-core host the
# CPU executor otherwise oversubscribes and both paths lose. See the heterogeneous
# subsection: this is a scheduling parameter, not a tuning trick.
CPU_THREADS=${FREP4_CPU_THREADS:-14}

mkdir -p "$OUT"
need() {
    [ -x "$BIN/$1" ] || { echo "missing $BIN/$1 — build the render targets first" >&2; exit 1; }
}

provenance() {
    {
        echo "# generated by paper_numbers.sh on $(date -Is)"
        echo "# commit: $(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
        echo "# host:   $(uname -sr) / $(nproc) cores"
        echo "# gpu:    $(nvidia-smi --query-gpu=name --format=csv,noheader 2>/dev/null || echo none)"
    } > "$1"
}

# ── Render cost per path, one resolution (the cross-system render table) ──────
do_render() {
    need frep4_pathcost
    f="$OUT/render_512.csv"; provenance "$f"; echo "$HDR,build_ms,run_ms" >> "$f"
    for s in $SCENES; do
        "$BIN/frep4_pathcost" "scenes/frep4/$s.json" 512 2>>"$f" >/dev/null
    done
    echo "-> $f"
}

# ── CPU vs GPU across frame sizes (the resolution-scaling table) ─────────────
do_resolution() {
    need frep4_pathcost
    f="$OUT/render_scaling.csv"; provenance "$f"; echo "$HDR,build_ms,run_ms" >> "$f"
    for r in 400 800 1280; do
        for s in $SCENES; do
            "$BIN/frep4_pathcost" "scenes/frep4/$s.json" "$r" 2>>"$f" >/dev/null
        done
    done
    echo "-> $f"
}

# ── Heterogeneous throughput + energy (shared tile queue) ────────────────────
do_hetero() {
    need frep4_tilequeue_bench
    f="$OUT/hetero_tilequeue.csv"; provenance "$f"; echo "$HDR" >> "$f"
    set -- ; for s in $SCENES; do set -- "$@" "scenes/frep4/$s.json"; done
    FREP4_CPU_THREADS="$CPU_THREADS" "$BIN/frep4_tilequeue_bench" "$@" \
        --res 800 --tile 128 --frames 10 --rounds 5 2>>"$f"
    echo "-> $f"
}

# ── RTX multi-BLAS instance scaling ─────────────────────────────────────────
do_rtx() {
    [ -x "$BIN/frep4/frep_rtx_bench" ] || {
        echo "skip rtx: $BIN/frep4/frep_rtx_bench not built" >&2; return 0; }
    f="$OUT/rtx_instances.txt"; provenance "$f"
    "$BIN/frep4/frep_rtx_bench" --energy >> "$f" 2>&1 || true
    echo "-> $f"
}

# ── Grid SDF-evaluation throughput (cross-system comparison) ────────────────
do_grid() {
    need frep4_bench_grid
    f="$OUT/grid_193.csv"; provenance "$f"; echo "$HDR" >> "$f"
    set -- ; for s in $SCENES; do set -- "$@" "scenes/frep4/$s.json"; done
    "$BIN/frep4_bench_grid" 193 "$@" >> "$f"
    echo "-> $f"
}

# ── Cross-system energy on one identical workload ───────────────────────────
# The energy axis is only meaningful across systems if the systems do the same
# work. The 193^3 grid is the one workload all three scalar evaluators perform
# (mpr is a GPU interval renderer and exposes no scalar evaluation), and the
# three agree on the field to ~1e-7, so the joules differ only in how each
# evaluates it. Energy is whole-package CPU (RAPL) plus GPU (NVML) over the run
# -- energy to complete the task, which is what a user pays.
do_energy() {
    need frep4_energy_wrap
    W="$BIN/frep4_energy_wrap"
    f="$OUT/energy_xsys.csv"; provenance "$f"; echo "$HDR" >> "$f"

    LB=libfive_bench/build/bench_libfive
    HF=hyperfun_bench/build/bench_hf
    if [ -x "$LB" ]; then
        export LD_LIBRARY_PATH="${LIBFIVE_ROOT:-$(pwd)/libfive}/build/libfive/src:$LD_LIBRARY_PATH"
        "$W" libfive cpu-array grid193 193 -- "$LB" --grid 193 >>"$f" 2>/dev/null
    else echo "skip libfive (not built)" >&2; fi

    if [ -x "$HF" ]; then
        set -- ; for s in $SCENES; do [ -f "scenes/hyperfun/$s.hf" ] && set -- "$@" "scenes/hyperfun/$s.hf"; done
        [ $# -gt 0 ] && "$W" hyperfun interpreter grid193 193 -- "$HF" 193 "$@" >>"$f" 2>/dev/null
    else echo "skip hyperfun (not built)" >&2; fi

    set -- ; for s in $SCENES; do set -- "$@" "scenes/frep4/$s.json"; done
    "$W" frep4 cpu_ir grid193 193 -- "$BIN/frep4_bench_grid" 193 "$@" >>"$f" 2>/dev/null
    echo "-> $f"
}

# ── Energy per render path (the CPU/GPU split of the energy axis) ───────────
# Both counters over a fixed-duration window per path: NVML integrates power on
# a ~10-100 ms cadence, so a few millisecond-scale frames sample nothing. CPU
# and GPU are reported separately because the package draws ~80 W on this host
# whatever the GPU is doing, so a single total would price a GPU path by how
# long the CPU waited for it.
do_pathenergy() {
    need frep4_pathcost
    f="$OUT/energy_paths.csv"; provenance "$f"
    echo "$HDR,gpu_j_per_frame,cpu_j_per_frame,build_ms,run_ms" >> "$f"
    for s in $SCENES; do
        "$BIN/frep4_pathcost" "scenes/frep4/$s.json" 512 --energy 6 2>>"$f" >/dev/null
    done
    echo "-> $f"
}

case "${1:-all}" in
    render)     do_render ;;
    resolution) do_resolution ;;
    hetero)     do_hetero ;;
    rtx)        do_rtx ;;
    grid)       do_grid ;;
    energy)     do_energy ;;
    pathenergy) do_pathenergy ;;
    all)        do_render; do_resolution; do_hetero; do_rtx; do_grid; do_energy; do_pathenergy ;;
    *) echo "usage: $0 [all|render|resolution|hetero|rtx|grid|energy|pathenergy]" >&2; exit 2 ;;
esac

echo "done — CSVs in $OUT/ (see $OUT/README.md for the table mapping)"
